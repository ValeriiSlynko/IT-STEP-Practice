-- 7. Виведіть назви відділень, які отримували пожертвування у розмірі понад 90000,
	-- із зазначенням їх лікарів.
	 SELECT DEP.NAME, DOC.NAME||' '||DOC.SURNAME AS FULL_NAME, DON.AMOUNT
	 FROM DEPARTMENTS DEP JOIN DOCTORS DOC ON DEP.ID = DOC.DEPARTMENT_ID
	 	JOIN DONATIONS DON ON DON.DEPARTMENT_ID = DEP.ID
	 	JOIN SPONSORS SP ON DEP.ID = SP.ID
	 WHERE DON.AMOUNT >= '90000'
	 ORDER BY DON.AMOUNT DESC

