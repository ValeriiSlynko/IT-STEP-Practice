-- Виконайте запити цього практичного завдання до бази
-- даних Лікарня (Hospital). Опис бази даних знаходиться в кінці файлу.
-- 1. Виведіть повні імена лікарів та їх спеціалізації.
	 SELECT DOC.NAME || ' ' || DOC.SURNAME AS FULL_NAME,
	 		SPEC.NAME AS SPECIALOZATION
	 FROM DOCTORSPECIALIZATIONS DOCSPEC JOIN DOCTORS DOC ON DOC.ID = DOCSPEC.ID
	 	JOIN SPECIALIZATIONS SPEC ON DOCSPEC.SPECIALIZATION_ID = SPEC.ID
	 WHERE SPEC.NAME = 'Cardiologist'

-- 2. Виведіть прізвища та зарплати (сума ставки та надбавки) лікарів, які перебувають у відпустці.
	 SELECT DOC.NAME||' '||DOC.SURNAME AS FULL_NAME, SALARY, PREMIUM, VAC.STARTDATE, VAC.ENDDATE
	 FROM DOCTORS DOC JOIN VACATIONS VAC ON DOC.ID = VAC.DOCTOR_ID
	 WHERE '2025-07-11' BETWEEN VAC.STARTDATE AND VAC.ENDDATE

-- 3. Виведіть назви палат, які знаходяться у відділенні «Intensive Treatment».
	 SELECT WAR.NAME, DEP.NAME
	 FROM WARDS WAR JOIN DEPARTMENTS DEP ON DEP.ID = WAR.DEPARTMENT_ID
	 WHERE DEP.NAME = 'Pediatrics'

-- 4. Виведіть назви відділень без повторень, які спонсоруються компанією «Umbrella Corporation».
	 SELECT DISTINCT DEP.NAME, SP.NAME
	 FROM DEPARTMENTS DEP JOIN DONATIONS DON ON DEP.ID = DON.ID
	 	JOIN SPONSORS SP ON DON.ID = SP.ID
	 WHERE SP.NAME = 'MediLife'

-- 5. Виведіть усі пожертвування за останній місяць у вигляді:
	-- відділення, спонсор, сума пожертвування, дата пожертвування.
	 SELECT DEP.NAME AS DEPARTMENT, SP.NAME AS SPONSOR, DON.AMOUNT, DON.DONATION_DATE
	 FROM DEPARTMENTS DEP JOIN DONATIONS DON ON DEP.ID = DON.DEPARTMENT_ID
	 	JOIN SPONSORS SP ON SP.ID = DON.SPONSOR_ID
	 WHERE DON.DONATION_DATE >= CURRENT_DATE - INTERVAL '18 month'

